begin
  function_definition := pg_get_functiondef(
    'recalculate_rankings(text)'::regprocedure
  );
  inputs_start := position('  ), inputs as (' in function_definition);
  founding_units_start := position('  with previous as (' in function_definition);

  if inputs_start = 0 or founding_units_start = 0
    or founding_units_start <= inputs_start then
    raise exception 'Unable to locate ranking inputs in recalculate_rankings';
  end if;

  function_definition :=
    substring(function_definition from 1 for inputs_start - 1)
    || replacement
    || substring(function_definition from founding_units_start);

  execute function_definition;
end;
