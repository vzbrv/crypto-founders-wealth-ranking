-- Forward-only confidence evidence. `projects.confidence_level` remains legacy
-- research metadata and must never determine rank eligibility.

create table project_confidence_evidence (
  id bigint generated by default as identity primary key,
  calculation_run_id uuid not null references calculation_runs(id),
  project_id uuid not null references projects(id),
  component text not null check (component in (
    'founder_identity_evidence',
    'founder_wallet_coverage',
    'team_foundation_treasury_coverage',
    'circulation_treatment',
    'funding_completeness',
    'market_reliability'
  )),
  maximum_score numeric(5, 2) not null check (maximum_score > 0),
  score numeric(5, 2) not null check (score >= 0 and score <= maximum_score),
  complete boolean not null,
  evidence jsonb not null default '[]'::jsonb
    check (jsonb_typeof(evidence) = 'array'),
  created_at timestamptz not null default now(),
  unique (calculation_run_id, project_id, component)
);

create index project_confidence_evidence_project_id_idx
  on project_confidence_evidence(project_id);

alter table project_confidence_evidence enable row level security;

comment on column projects.confidence_level is
  'Legacy research metadata. SQL-derived confidence evidence controls eligibility.';

